// Generate TypeScript types from /contracts/*.schema.json (source: engine Pydantic models).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const contractsDir = join(here, '..', '..', 'contracts')
export const outFile = join(here, '..', 'src', 'renderer', 'src', 'lib', 'contracts.gen.ts')

/** Remove Pydantic's per-property `title`s so we don't get `type Title = string` noise. */
function stripTitles(node, isDefRoot = false) {
  if (Array.isArray(node)) return node.map((n) => stripTitles(n))
  if (node && typeof node === 'object') {
    // `{ $ref, default }` siblings make the generator emit duplicate aliases (Priority1...).
    if (node.$ref) return { $ref: node.$ref }
    const out = {}
    for (const [k, v] of Object.entries(node)) {
      if (k === 'title' && !isDefRoot) continue
      if (k === 'properties') {
        out[k] = Object.fromEntries(Object.entries(v).map(([n, d]) => [n, stripTitles(d)]))
      } else if (k === '$defs') {
        out[k] = Object.fromEntries(Object.entries(v).map(([n, d]) => [n, stripTitles(d, true)]))
      } else {
        out[k] = stripTitles(v)
      }
    }
    return out
  }
  return node
}

export async function render() {
  const files = readdirSync(contractsDir).filter((f) => f.endsWith('.schema.json')).sort()
  const defs = {}
  for (const file of files) {
    const { $schema: _s, $id: _i, $defs = {}, ...root } = JSON.parse(readFileSync(join(contractsDir, file), 'utf8'))
    Object.assign(defs, $defs)
    defs[root.title] = root
  }
  const combined = stripTitles({
    title: 'HarkContracts',
    type: 'object',
    additionalProperties: false,
    properties: Object.fromEntries(Object.keys(defs).map((n) => [n, { $ref: `#/$defs/${n}` }])),
    $defs: defs,
  }, true)
  const ts = await compile(combined, 'HarkContracts', {
    bannerComment: '/* eslint-disable */\n// GENERATED by scripts/gen-contract-types.mjs from /contracts. Do not edit.',
    additionalProperties: false,
    unreachableDefinitions: true,
  })
  return ts.replace(/export interface HarkContracts \{[\s\S]*?\n\}\n/, '')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outFile, await render())
  console.log(`wrote ${outFile}`)
}
